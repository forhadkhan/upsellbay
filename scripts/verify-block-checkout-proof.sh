#!/usr/bin/env bash
set -e

# Runs the Block Checkout E2E spec against real env vars and writes a dated,
# commit-pinned evidence file. This is the only source of truth the
# "block checkout compatibility is declared after e2e proof passes" gate in
# tests/test-quality-assurance.php should trust — do not hand-edit the
# evidence JSON to "pass" the gate; regenerate it by actually running this.

REQUIRED_VARS=(UPSELLBAY_E2E_BASE_URL UPSELLBAY_E2E_ADMIN_USER UPSELLBAY_E2E_ADMIN_PASS UPSELLBAY_E2E_BLOCK_CHECKOUT_URL)
for var in "${REQUIRED_VARS[@]}"; do
	if [ -z "${!var}" ]; then
		echo "❌ $var is not set. Export UPSELLBAY_E2E_BASE_URL, UPSELLBAY_E2E_ADMIN_USER, UPSELLBAY_E2E_ADMIN_PASS, UPSELLBAY_E2E_BLOCK_CHECKOUT_URL (and UPSELLBAY_E2E_PRODUCT_URL/CART_URL/CHECKOUT_URL) before running this."
		exit 1
	fi
done

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
EVIDENCE="$ROOT/tests/e2e/evidence/block-checkout-proof.json"
SPEC="tests/e2e/block-checkout.spec.js"

cd "$ROOT"

set +e
RUN_OUTPUT=$(npx playwright test "$SPEC" --project=chromium-desktop --reporter=json 2>/tmp/upsellbay-block-checkout-stderr)
RUN_EXIT=$?
set -e

TOTAL=$(echo "$RUN_OUTPUT" | node -e "let d='';process.stdin.on('data',c=>d+=c);process.stdin.on('end',()=>{const j=JSON.parse(d);console.log(j.stats.expected+j.stats.unexpected+j.stats.flaky+j.stats.skipped)})" 2>/dev/null || echo 0)
PASSED=$(echo "$RUN_OUTPUT" | node -e "let d='';process.stdin.on('data',c=>d+=c);process.stdin.on('end',()=>{const j=JSON.parse(d);console.log(j.stats.expected)})" 2>/dev/null || echo 0)
FAILED=$(echo "$RUN_OUTPUT" | node -e "let d='';process.stdin.on('data',c=>d+=c);process.stdin.on('end',()=>{const j=JSON.parse(d);console.log(j.stats.unexpected)})" 2>/dev/null || echo 0)

COMMIT=$(git rev-parse HEAD)
RAN_AT=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

cat > "$EVIDENCE" <<EOF
{
  "spec": "$SPEC",
  "project": "chromium-desktop",
  "ranAt": "$RAN_AT",
  "commit": "$COMMIT",
  "total": $TOTAL,
  "passed": $PASSED,
  "failed": $FAILED,
  "notes": "Generated by scripts/verify-block-checkout-proof.sh. Update this file only by re-running that script; do not hand-edit it to force the compatibility gate to pass."
}
EOF

echo "Evidence written to $EVIDENCE"

if [ "$RUN_EXIT" -ne 0 ]; then
	echo "❌ Block Checkout E2E spec failed ($FAILED failed / $TOTAL total). Evidence recorded as failing."
	exit 1
fi

echo "✅ Block Checkout E2E spec passed ($PASSED/$TOTAL)."
